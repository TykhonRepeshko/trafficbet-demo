param(
    [switch]$IntegrationTests,
    [Alias('PreviewBuild')][switch]$Preview
)

$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'node-tools.ps1')
$checkRoot = Split-Path -Parent $PSScriptRoot
$results = [Collections.Generic.List[object]]::new()
$redactedValues = [Collections.Generic.List[string]]::new()
$changedEnvironment = @(
    'TEST_DATABASE_URL', 'DATABASE_URL', 'MFA_ENCRYPTION_KEY', 'RESTORE_DATABASE_URL', 'WORKER_TOKEN', 'POSTGRES_RUNTIME_PASSWORD', 'DEMO_ADMIN_PASSWORD',
    'DEMO_PLAYER_PASSWORD', 'POSTGRES_PASSWORD', 'PGPASSWORD', 'PGCONNECT_TIMEOUT',
    'GOCACHE', 'GOMODCACHE', 'GOPATH', 'NG_CLI_ANALYTICS', 'CI', 'PATH', 'VIDEO_DECODER_TEST_PATH'
)
$savedEnvironment = @{}
foreach ($key in $changedEnvironment) {
    $savedEnvironment[$key] = [Environment]::GetEnvironmentVariable($key, 'Process')
}

function Protect-CheckOutput([string]$Value) {
    foreach ($secret in $redactedValues) {
        if ($secret) { $Value = $Value.Replace($secret, '[redacted]') }
    }
    return $Value
}

function Invoke-ProjectCheck([string]$Name, [scriptblock]$Action) {
    Write-Host "Checking: $Name"
    $timer = [Diagnostics.Stopwatch]::StartNew()
    try {
        & $Action
        $results.Add([pscustomobject]@{ Check = $Name; Result = 'PASS'; Seconds = [Math]::Round($timer.Elapsed.TotalSeconds, 1); Detail = '' })
    } catch {
        $detail = Protect-CheckOutput $_.Exception.Message
        $results.Add([pscustomobject]@{ Check = $Name; Result = 'FAIL'; Seconds = [Math]::Round($timer.Elapsed.TotalSeconds, 1); Detail = $detail })
        Write-Host "FAIL: $Name - $detail" -ForegroundColor Red
    }
}

function Add-SkippedCheck([string]$Name, [string]$Detail) {
    $results.Add([pscustomobject]@{ Check = $Name; Result = 'SKIP'; Seconds = 0; Detail = $Detail })
}

function Invoke-GoSuite([string]$Name, [string[]]$ExtraArguments, [bool]$RequireIntegration) {
    Push-Location (Join-Path $checkRoot 'backend')
    try {
        # JSON reports distinguish actual test runs, skips and package failures.
        # Keep results in memory; no database credentials are written to a log.
        $events = @(& $script:checkGoPath test -json -count=1 -timeout=180s @ExtraArguments ./... 2>&1)
        $testExitCode = $LASTEXITCODE
    } finally { Pop-Location }
    $passed = 0
    $skipped = 0
    $integrationPassed = 0
    $integrationSkipped = 0
    $failureOutput = [Collections.Generic.List[string]]::new()
    $testOutput = @{}
    foreach ($line in $events) {
        try { $event = [string]$line | ConvertFrom-Json -ErrorAction Stop } catch {
            $failureOutput.Add((Protect-CheckOutput ([string]$line)))
            continue
        }
        $testName = [string]$event.Test
        if ($event.Action -eq 'output') {
            $eventKey = [string]$event.Package + '/' + $testName
            if (-not $testOutput.ContainsKey($eventKey)) { $testOutput[$eventKey] = [Collections.Generic.List[string]]::new() }
            $testOutput[$eventKey].Add((Protect-CheckOutput ([string]$event.Output).TrimEnd()))
        }
        if ($testName -and $event.Action -eq 'pass') {
            $passed++
            if ($testName -match '^TestPostgres[^/]*$') { $integrationPassed++ }
        }
        if ($testName -and $event.Action -eq 'skip') {
            $skipped++
            if ($testName -match '^TestPostgres') { $integrationSkipped++ }
        }
        if ($event.Action -eq 'fail') {
            $eventKey = [string]$event.Package + '/' + $testName
            if ($testOutput.ContainsKey($eventKey)) {
                foreach ($outputLine in $testOutput[$eventKey]) { $failureOutput.Add($outputLine) }
            }
        }
    }
    Write-Host "$Name`: $passed passed; $skipped skipped."
    if ($testExitCode -ne 0) {
        foreach ($outputLine in ($failureOutput | Select-Object -Last 40)) { Write-Host $outputLine }
        throw "Go tests failed with exit code $testExitCode."
    }
    if ($passed -eq 0) { throw 'No tests ran successfully.' }
    if ($RequireIntegration -and ($integrationPassed -eq 0 -or $integrationSkipped -gt 0)) {
        throw "Integration tests were not fully executed: $integrationPassed passed; $integrationSkipped skipped."
    }
}

function Set-IsolatedTestDatabase {
    $password = $null
    $envFile = Join-Path $checkRoot '.env'
    if (-not (Test-Path -LiteralPath $envFile)) { throw 'Integration tests require the local .env generated by scripts/setup.ps1.' }
    foreach ($line in Get-Content -LiteralPath $envFile) {
        if ($line -match '^POSTGRES_PASSWORD=(.+)$') { $password = $Matches[1] }
    }
    if (-not $password -or $password -notmatch '^[a-zA-Z0-9_-]{32,}$') {
        throw 'Integration checks require the generated URL-safe POSTGRES_PASSWORD in .env.'
    }
    $redactedValues.Add($password)
    $psql = Join-Path $checkRoot '.tools/postgresql-runtime/pgsql/bin/psql.exe'
    $expectedCluster = Join-Path $checkRoot '.tools/pgdata-qa'
    if (-not (Test-Path -LiteralPath $psql) -or -not (Test-Path -LiteralPath (Join-Path $expectedCluster 'PG_VERSION'))) {
        throw 'The isolated PostgreSQL QA runtime/cluster is missing. See docs/09-testing.md; application data is never used as a fallback.'
    }
    $env:PGPASSWORD = $password
    $env:PGCONNECT_TIMEOUT = '5'
    # Fixed host, port and database: never reuse DATABASE_URL or the application
    # cluster on 55433. -X prevents an unrelated psql startup script from running.
    $cluster = @(& $psql -X --no-password -h 127.0.0.1 -p 55432 -U trafficbet -d trafficbet_tests -v ON_ERROR_STOP=1 -tAc 'SHOW data_directory' 2>&1)
    $connectionExit = $LASTEXITCODE
    if ($connectionExit -ne 0) { throw 'Cannot connect to the isolated trafficbet_tests database on 127.0.0.1:55432. Start its QA cluster first; see docs/09-testing.md.' }
    $actualCluster = ($cluster -join "`n").Trim()
    try {
        $matchesCluster = [StringComparer]::OrdinalIgnoreCase.Equals(
            [IO.Path]::GetFullPath($actualCluster), [IO.Path]::GetFullPath($expectedCluster)
        )
    } catch { $matchesCluster = $false }
    if (-not $matchesCluster) { throw 'Port 55432 is not the expected .tools/pgdata-qa cluster. Integration tests were refused before creating test schemas.' }
    $env:TEST_DATABASE_URL = "postgres://trafficbet:$password@127.0.0.1:55432/trafficbet_tests?sslmode=disable"
    $env:PGPASSWORD = $null
}

try {
    # An inherited connection or token must not silently select a real database
    # or reach frontend build plugins. Only the integration phase receives a URL.
    foreach ($key in @('TEST_DATABASE_URL', 'DATABASE_URL', 'MFA_ENCRYPTION_KEY', 'RESTORE_DATABASE_URL', 'WORKER_TOKEN', 'POSTGRES_RUNTIME_PASSWORD', 'DEMO_ADMIN_PASSWORD', 'DEMO_PLAYER_PASSWORD', 'POSTGRES_PASSWORD', 'PGPASSWORD')) {
        $value = [Environment]::GetEnvironmentVariable($key, 'Process')
        if ($value) { $redactedValues.Add($value) }
        [Environment]::SetEnvironmentVariable($key, $null, 'Process')
    }
    $env:GOCACHE = Join-Path $checkRoot '.tools/go-cache'
    $env:GOMODCACHE = Join-Path $checkRoot '.tools/go-mod'
    $env:GOPATH = Join-Path $checkRoot '.tools/go-path'
    $env:NG_CLI_ANALYTICS = 'false'
    $env:CI = 'true'
    $decoderCandidates = @(Get-ChildItem -Path (Join-Path $checkRoot '.tools/ffmpeg/*/bin/ffmpeg.exe') -ErrorAction SilentlyContinue)
    $env:VIDEO_DECODER_TEST_PATH = if ($decoderCandidates.Count -eq 1) { $decoderCandidates[0].FullName } else { $null }
    $goCommand = Get-Command go.exe -ErrorAction SilentlyContinue
    $script:checkGoPath = if ($goCommand) { $goCommand.Source } else { Join-Path $checkRoot '.tools/go/bin/go.exe' }

    Invoke-ProjectCheck 'Go unit tests (database disabled)' {
        if (-not (Test-Path -LiteralPath $script:checkGoPath)) { throw 'Go is missing. Install the version in backend/go.mod or prepare .tools/go.' }
        Invoke-GoSuite 'Unit suite' @() $false
    }
    Invoke-ProjectCheck 'Go vet' {
        Push-Location (Join-Path $checkRoot 'backend')
        try {
            & $script:checkGoPath vet ./...
            if ($LASTEXITCODE -ne 0) { throw "Go vet failed with exit code $LASTEXITCODE." }
        } finally { Pop-Location }
    }
    if ($IntegrationTests) {
        Invoke-ProjectCheck 'PostgreSQL integration tests (isolated QA cluster)' {
            try {
                Set-IsolatedTestDatabase
                Invoke-GoSuite 'PostgreSQL suite' @('-run', '^TestPostgres') $true
            } finally { $env:TEST_DATABASE_URL = $null; $env:PGPASSWORD = $null }
        }
    } else { Add-SkippedCheck 'PostgreSQL integration tests' 'Opt in with -IntegrationTests; no database connection was used.' }

    Invoke-ProjectCheck 'Angular regression tests (Node.js 24)' {
        if (-not (Test-Path -LiteralPath (Join-Path $checkRoot 'frontend/node_modules'))) { throw 'Frontend dependencies are missing. Run npm ci in frontend before checking; checks do not install packages.' }
        $testNodePath = Get-ProjectNode
        Push-Location (Join-Path $checkRoot 'frontend')
        try {
            $testFiles = @(Get-ChildItem -LiteralPath src/app/tests -Filter '*.test.mjs' | Sort-Object Name | ForEach-Object FullName)
            if ($testFiles.Count -eq 0) { throw 'No Angular regression test files were found.' }
            & $testNodePath --test @testFiles
            if ($LASTEXITCODE -ne 0) { throw "Angular regression tests failed with exit code $LASTEXITCODE." }
        } finally { Pop-Location }
    }
    Invoke-ProjectCheck 'Angular production build' {
        if (-not (Test-Path -LiteralPath (Join-Path $checkRoot 'frontend/node_modules'))) { throw 'Frontend dependencies are missing. Run npm ci in frontend before checking; checks do not install packages.' }
        Push-Location (Join-Path $checkRoot 'frontend')
        try { Invoke-ProjectNpm run build } finally { Pop-Location }
    }
    if ($Preview) {
        Invoke-ProjectCheck 'Angular design preview build' {
            Push-Location (Join-Path $checkRoot 'frontend')
            # Keep preview output separate from the deployable production build.
            try { Invoke-ProjectNpm -NpmArguments @('run', 'build:preview', '--', '--output-path', 'dist/trafficbet-preview') } finally { Pop-Location }
        }
    } else { Add-SkippedCheck 'Angular design preview build' 'Opt in with -Preview.' }

    $dockerCommand = Get-Command docker.exe -ErrorAction SilentlyContinue
    $dockerPath = if ($dockerCommand) { $dockerCommand.Source } else { $null }
    if (-not $dockerPath) {
        foreach ($candidate in @((Join-Path $env:ProgramFiles 'Docker/Docker/resources/bin/docker.exe'), (Join-Path $env:LOCALAPPDATA 'Programs/DockerDesktop/resources/bin/docker.exe'))) {
            if (Test-Path -LiteralPath $candidate) { $dockerPath = $candidate; break }
        }
    }
    $composeCommand = Get-Command docker-compose.exe -ErrorAction SilentlyContinue
    $composePath = if ($composeCommand) { $composeCommand.Source } else { Join-Path $checkRoot '.tools/docker-compose.exe' }
    if ($dockerPath -or (Test-Path -LiteralPath $composePath)) {
        Invoke-ProjectCheck 'Docker Compose configurations (syntax only)' {
            # Validate required interpolation with non-secret process values.
            $env:POSTGRES_PASSWORD = 'verification-only-placeholder-password'
            $env:POSTGRES_RUNTIME_PASSWORD = 'verification-only-runtime-placeholder-password'
            $env:WORKER_TOKEN = 'verification-only-placeholder-worker-token'
            Push-Location $checkRoot
            try {
                foreach ($file in @('docker-compose.yml', 'docker-compose.test.yml')) {
                    if ($dockerPath) { & $dockerPath compose -f $file config -q }
                    else { & $composePath -f $file config -q }
                    if ($LASTEXITCODE -ne 0) { throw "Compose configuration failed: $file." }
                }
            } finally { Pop-Location; $env:POSTGRES_PASSWORD = $null; $env:POSTGRES_RUNTIME_PASSWORD = $null; $env:WORKER_TOKEN = $null }
        }
    } else { Add-SkippedCheck 'Docker Compose configurations' 'Docker/Compose CLI is unavailable.' }

    if ($dockerPath) {
        $process = [Diagnostics.Process]::new()
        try {
            $process.StartInfo.FileName = $dockerPath
            $process.StartInfo.Arguments = 'info --format "{{.ServerVersion}}"'
            $process.StartInfo.UseShellExecute = $false
            $process.StartInfo.CreateNoWindow = $true
            $process.StartInfo.RedirectStandardOutput = $true
            $process.StartInfo.RedirectStandardError = $true
            [void]$process.Start()
            $stdoutTask = $process.StandardOutput.ReadToEndAsync()
            $stderrTask = $process.StandardError.ReadToEndAsync()
            if (-not $process.WaitForExit(8000)) { $process.Kill(); [void]$process.WaitForExit(1000); $engineReady = $false }
            else { $engineReady = $process.ExitCode -eq 0 }
            if ($engineReady) { Add-SkippedCheck 'Docker container runtime tests' 'Engine is available; containers were not started. See docs/09-testing.md for the isolated Compose test command.' }
            else { Add-SkippedCheck 'Docker container runtime tests' 'Docker engine is unavailable; syntax validation does not verify containers.' }
        } catch { Add-SkippedCheck 'Docker container runtime tests' 'Docker engine readiness could not be checked; containers were not run.' }
        finally { $process.Dispose() }
    } else { Add-SkippedCheck 'Docker container runtime tests' 'Docker is not installed; containers were not run.' }
    Add-SkippedCheck 'Browser visual/click checks' 'Not part of this runner. Build/API checks do not verify rendered layouts or player interaction.'
} finally {
    foreach ($key in $changedEnvironment) {
        [Environment]::SetEnvironmentVariable($key, $savedEnvironment[$key], 'Process')
    }
}

Write-Host ''
Write-Host 'Project check results'
$results | Format-Table Check, Result, Seconds, Detail -AutoSize -Wrap | Out-Host
$failedCount = @($results | Where-Object Result -eq 'FAIL').Count
$skippedCount = @($results | Where-Object Result -eq 'SKIP').Count
Write-Host "Failed checks: $failedCount. Skipped checks: $skippedCount. A skipped check is not a pass."
if ($failedCount -gt 0) { exit 1 }
exit 0
